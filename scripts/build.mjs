#!/usr/bin/env node
// Zero-dependency build: tokens/tokens.json + src/ -> dist/
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const tokens = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const dist = join(root, 'dist');

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'fonts'), { recursive: true });

const banner = `/* Ground Control UI v${pkg.version} — generated by scripts/build.mjs, do not edit */\n`;

// ---------- tokens.css ----------
const themes = tokens.color.themes;
const first = themes[0].id;
const colorVal = (t, theme) => (typeof t.value === 'string' ? (theme === first ? t.value : null) : t.value[theme] ?? null);
const resolve = (v) => (/^\{.+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v);

// All tokens are emitted as --gc-<name>. The unprefixed names from v0.1 are kept as
// deprecated aliases so existing consumers don't break; they will be removed in v1.0.
const legacy = [];
// Spacing/radius names that existed in v0.1 (only these get unprefixed aliases).
const V01_NAMES = new Set(['space-1', 'space-2', 'space-4', 'space-6', 'radius-sm', 'radius-md', 'radius-lg']);
let css = banner;
css += `:root, [data-theme="${first}"] {\n`;
for (const t of tokens.color.tokens) {
  css += `  --gc-${t.name}: ${resolve(colorVal(t, first))};\n`;
  legacy.push(t.name);
}
css += `}\n`;
for (const th of themes.slice(1)) {
  css += `[data-theme="${th.id}"] {\n`;
  for (const t of tokens.color.tokens) {
    const v = colorVal(t, th.id);
    if (v) css += `  --gc-${t.name}: ${resolve(v)};\n`;
  }
  css += `}\n`;
}
css += `:root {\n`;
for (const fam of ['spacing', 'radius']) {
  for (const t of tokens[fam]?.tokens ?? []) {
    css += `  --gc-${t.name}: ${t.value};\n`;
    if (V01_NAMES.has(t.name)) legacy.push(t.name);
  }
}
for (const [k, v] of Object.entries(tokens.type.families)) {
  css += `  --gc-font-${k}: ${v};\n`;
  legacy.push(`font-${k}`);
}
css += `}\n`;
css += `/* deprecated v0.1 aliases — use --gc-* instead; removed in v1.0 */\n:root {\n`;
for (const n of legacy) css += `  --${n}: var(--gc-${n});\n`;
css += `}\n`;
for (const g of tokens.type.groups) {
  for (const s of g.styles) {
    css += `.gc-${s.name} {\n  font-family: var(--gc-font-${s.family ?? g.family});\n  font-size: ${s.fontSize};\n  line-height: ${s.lineHeight};\n  font-weight: ${s.fontWeight};\n`;
    if (s.letterSpacing) css += `  letter-spacing: ${s.letterSpacing};\n`;
    if (s.name === 'label') css += `  text-transform: uppercase;\n`;
    if (g.family === 'mono') css += `  font-variant-numeric: tabular-nums;\n`;
    css += `}\n`;
  }
}
writeFileSync(join(dist, 'tokens.css'), css);

// ---------- fonts.css (offline, self-hosted) ----------
const RANGES = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  cyrillic: 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
};
const FAMILIES = { 'ibm-plex-sans': 'IBM Plex Sans', 'jetbrains-mono': 'JetBrains Mono' };
let fonts = banner;
for (const f of readdirSync(join(root, 'fonts')).sort()) {
  copyFileSync(join(root, 'fonts', f), join(dist, 'fonts', f));
  const m = /^(.+)-(latin|cyrillic)-(\d{3})-normal\.woff2$/.exec(f);
  if (!m) continue;
  fonts += `@font-face {\n  font-family: '${FAMILIES[m[1]]}';\n  font-style: normal;\n  font-weight: ${m[3]};\n  font-display: swap;\n  src: url(./fonts/${f}) format('woff2');\n  unicode-range: ${RANGES[m[2]]};\n}\n`;
}
writeFileSync(join(dist, 'fonts.css'), fonts);

// ---------- ground-control.css (all-in-one) ----------
const base = readFileSync(join(root, 'src/css/base.css'), 'utf8');
writeFileSync(join(dist, 'ground-control.css'), fonts + css.replace(banner, '') + base);

// ---------- ground-control.js (all components, classic script or module) ----------
const compDir = join(root, 'src/components');
const comps = readdirSync(compDir).filter((f) => f.endsWith('.js')).sort();
let js = banner + `(function () {\n'use strict';\n`;
for (const f of comps) js += `\n// ---- ${f} ----\n` + readFileSync(join(compDir, f), 'utf8');
js += `\n})();\n`;
writeFileSync(join(dist, 'ground-control.js'), js);

console.log(`built dist/ — ${tokens.color.tokens.length} colors, ${comps.length} components, v${pkg.version}`);
